    private void editBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_editBtnActionPerformed
        int selectedRow = reportsTable.getSelectedRow();
        if (selectedRow < 0) {
            JOptionPane.showMessageDialog(this, "Please select a report to edit.", "Selection Error", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        if (isClaimMode()) {
            editClaim(selectedRow);
        } else {
            editItemReport(selectedRow);
        }
    }//GEN-LAST:event_editBtnActionPerformed

    private void deleteBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteBtnActionPerformed
        int selectedRow = reportsTable.getSelectedRow();
        if (selectedRow < 0) {
            JOptionPane.showMessageDialog(this, "Please select a report to delete.", "Selection Error", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        String userID = getUserIDOrRedirect();
        if (userID == null) {
            return;
        }
        
        int confirm = JOptionPane.showConfirmDialog(this, "Delete selected report?", "Confirm Delete", JOptionPane.YES_NO_OPTION);
        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }
        
        boolean success;
        if (isClaimMode()) {
            String claimID = reportsTable.getValueAt(selectedRow, 0).toString();
            success = new ClaimDA().deleteUserClaim(claimID, userID);
        } else {
            String itemID = reportsTable.getValueAt(selectedRow, 0).toString();
            success = new ItemDA().deleteUserItemReport(itemID, userID);
        }
        
        if (success) {
            JOptionPane.showMessageDialog(this, "Report deleted successfully.", "Success", JOptionPane.INFORMATION_MESSAGE);
            loadReports();
        } else {
            JOptionPane.showMessageDialog(this, "Delete failed. Claims can only be deleted while PENDING.", "Delete Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_deleteBtnActionPerformed

