    private String getUserIDOrRedirect() {
        String userID = SessionManager.getInstance().getAccountID();
        if (userID == null) {
            JOptionPane.showMessageDialog(this, "Please log in to manage reports.", "Session Error", JOptionPane.ERROR_MESSAGE);
            Login login = new Login();
            login.setVisible(true);
            this.dispose();
        }
        return userID;
    }
    
    private boolean isClaimMode() {
        return reportTypeComboBox.getSelectedIndex() == 1;
    }
    
    private void loadReports() {
        String userID = getUserIDOrRedirect();
        if (userID == null) {
            return;
        }
        
        if (isClaimMode()) {
            ClaimDA claimDA = new ClaimDA();
            reportsTable.setModel(claimDA.getClaimsByUserTableModel(userID));
        } else {
            ItemDA itemDA = new ItemDA();
            reportsTable.setModel(itemDA.getUserItemsManagementTableModel(userID));
        }
    }

