    private void editItemReport(int selectedRow) {
        String userID = getUserIDOrRedirect();
        if (userID == null) {
            return;
        }
        
        String itemID = reportsTable.getValueAt(selectedRow, 0).toString();
        String currentName = valueAt(selectedRow, 2);
        String currentDescription = valueAt(selectedRow, 3);
        String currentColor = valueAt(selectedRow, 5);
        String currentLocation = valueAt(selectedRow, 6);
        
        String itemName = JOptionPane.showInputDialog(this, "Item name:", currentName);
        if (itemName == null) return;
        String description = JOptionPane.showInputDialog(this, "Description:", currentDescription);
        if (description == null) return;
        String color = JOptionPane.showInputDialog(this, "Color:", currentColor);
        if (color == null) return;
        String location = JOptionPane.showInputDialog(this, "Location:", currentLocation);
        if (location == null) return;
        
        if (itemName.trim().isEmpty() || location.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Item name and location cannot be empty.", "Validation Error", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        boolean success = new ItemDA().updateUserItemReport(
                itemID, userID, itemName.trim(), description.trim(), color.trim(), location.trim());
        
        if (success) {
            JOptionPane.showMessageDialog(this, "Item report updated successfully.", "Success", JOptionPane.INFORMATION_MESSAGE);
            loadReports();
        } else {
            JOptionPane.showMessageDialog(this, "Update failed.", "Database Error", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void editClaim(int selectedRow) {
        String userID = getUserIDOrRedirect();
        if (userID == null) {
            return;
        }
        
        String claimID = reportsTable.getValueAt(selectedRow, 0).toString();
        String currentProof = valueAt(selectedRow, 2);
        String proof = JOptionPane.showInputDialog(this, "Proof of ownership:", currentProof);
        if (proof == null) {
            return;
        }
        
        if (proof.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Proof cannot be empty.", "Validation Error", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        boolean success = new ClaimDA().updateUserClaimProof(claimID, userID, proof.trim());
        
        if (success) {
            JOptionPane.showMessageDialog(this, "Claim proof updated successfully.", "Success", JOptionPane.INFORMATION_MESSAGE);
            loadReports();
        } else {
            JOptionPane.showMessageDialog(this, "Update failed. Claims can only be edited while PENDING.", "Update Error", JOptionPane.ERROR_MESSAGE);
        }
    }
    
    private String valueAt(int row, int column) {
        Object value = reportsTable.getValueAt(row, column);
        return value == null ? "" : value.toString();
    }

